// Browser walk-through on an iPhone: first run, shelve + open packs, binder, PSA grading + reveal,
// deals board, distributor, customers. Usage: PLAYWRIGHT_PATH=$(npm root -g)/playwright node tools/smoke.mjs [baseUrl] [outDir]
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
const require = createRequire(import.meta.url);
const { chromium, devices } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const base = process.argv[2] || 'http://localhost:4174/';
const out = process.argv[3] || 'tests/output';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices['iPhone 13'] });
const page = await ctx.newPage();
const errors = [];
const results = [];
const check = (name, ok, detail = '') => results.push(`${ok ? 'PASS' : 'FAIL'} ${name} ${detail}`);
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error' && !m.text().includes('Failed to load resource')) errors.push(m.text()); });
const click = (text, sel = 'button') => page.evaluate(([t, s]) => {
  const el = [...document.querySelectorAll(s)].find((x) => x.textContent.trim().includes(t));
  if (!el) return false; el.click(); return true;
}, [text, sel]);
const shot = (n) => page.screenshot({ path: `${out}/${n}.png` });
await page.goto(base + '?debug');
await page.waitForSelector('.top', { timeout: 30000 });
await page.waitForTimeout(800);
await shot('01-first-run');
check('first run', await click('Open my first pack'));
await page.waitForTimeout(400);
// Put Unleashed packs on the shelf at a fair price
check('shelve', await click('Put on shelf'));
await page.waitForTimeout(300);
await shot('02-shelve');
check('confirm shelve', await click('on the shelf'));
await page.waitForTimeout(300);
await shot('03-stock');
// Open Vendetta packs
check('open', await click('Open', '.sealed-row button.primary'));
await page.waitForTimeout(400);
await shot('04-pack');
await page.click('.tear-pack', { force: true });
await page.waitForTimeout(400);
for (let i = 0; i < 14; i++) { await page.click('.reveal-card', { force: true }); await page.waitForTimeout(80); }
await page.waitForTimeout(300);
await shot('05-pack-summary');
await click('Done');
// Grade the best card with PSA, the next with Beckett
await page.click('.grid4 .slot');
await page.waitForTimeout(300);
check('grading locked at level 1', await page.evaluate(() => [...document.querySelectorAll('.modal button')].some((b) => b.disabled && b.textContent.includes('Lv 3'))));
await page.click('.modal .x');
// Skip ahead to level 12 so every grading tier is open.
await page.evaluate(() => { const s = window.__store; const g = s.getState().g; g.level = 12; g.levelUps = []; s.setState({ rev: s.getState().rev + 1 }); });
await page.waitForTimeout(200);
await page.click('.grid4 .slot');
await page.waitForTimeout(300);
check('grade it', await click('Grade it'));
await page.waitForTimeout(200);
await click('Express');
await page.waitForTimeout(200);
await shot('06-grade-psa');
check('send PSA', await click('Send to PSA'));
await page.waitForTimeout(200);
await page.click('.modal .x');
await page.click('.grid4 .slot');
await page.waitForTimeout(300);
await click('Grade it');
await click('BECKETT');
await click('Express');
await page.waitForTimeout(200);
await shot('07-grade-bgs');
check('send BGS', await click('Send to BGS'));
await page.click('.modal .x');
// Fast-forward a shop day: grades come back
await page.evaluate(() => window.__advance(13));
await page.waitForTimeout(600);
check('grade reveal', await page.evaluate(() => !!document.querySelector('.grade-pop')));
await shot('08-reveal');
await click('Next slab');
await page.waitForTimeout(600);
await shot('09-reveal-2');
await click('Nice');
await click('Grading', 'nav button');
await page.waitForTimeout(300);
await shot('10-slabs');
check('slabs shown', await page.evaluate(() => document.querySelectorAll('.slab').length >= 2));
// Put a slab in the display case
await page.click('.slab-grid > div');
await page.waitForTimeout(300);
await click('Put in display case');
await click('Confirm');
await page.waitForTimeout(200);
await page.click('.modal .x').catch(() => {});
await click('Market', 'nav button');
await page.waitForTimeout(400);
await shot('11-market');
check('buy deal', await page.evaluate(() => { const b = document.querySelector('.deal button:not([disabled])'); if (!b) return false; b.click(); return true; }));
await click('Shop', 'nav button');
await page.waitForTimeout(300);
// Fill the display case from the store: tap an empty spot, pick a card, price it.
check('case picker', await page.evaluate(() => { const b = document.querySelector('.case-spot.empty'); if (!b) return false; b.click(); return true; }));
await page.waitForTimeout(300);
await page.click('.pick-cards .pick');
await page.waitForTimeout(300);
await shot('12a-case-sheet');
check('put in case', await click('Put in the display case'));
await page.waitForTimeout(300);
await page.evaluate(() => window.__advance(3));
await page.waitForTimeout(500);
await page.evaluate(() => document.querySelector('.content').scrollTo(0, 0));
await shot('12-shop');
check('customers bought', await page.evaluate(() => window.__store.getState().g.stats.sales > 0), String(await page.evaluate(() => window.__store.getState().g.stats.sales)));
// Phase 2: build mode — buy a plant, see the floor and the customer mix
await click('Shop', 'nav button');
await page.waitForTimeout(300);
check('build sheet', await click('🛠 Build'));
await page.waitForTimeout(300);
await shot('12b-build');
await page.click('.tile.empty');
await page.waitForTimeout(200);
check('catalog', await page.evaluate(() => document.querySelectorAll('.cat-row').length >= 8));
await shot('12c-catalog');
const before = await page.evaluate(() => window.__store.getState().g.furniture.length);
await page.evaluate(() => { const row = [...document.querySelectorAll('.cat-row')].find((r) => r.textContent.includes('Potted plant')); row.querySelector('button').click(); });
await page.waitForTimeout(200);
check('bought furniture', await page.evaluate((n) => window.__store.getState().g.furniture.length === n + 1, before));
await page.click('.modal .x');
// Card requests: give the player the requested card, hand it over
await page.evaluate(() => { const s = window.__store; const g = s.getState().g; const r = g.requests[0]; if (r) { const e = g.cards[r.cardId] ?? [0, 0]; e[r.foil ? 1 : 0]++; g.cards[r.cardId] = e; } s.setState({ rev: s.getState().rev + 1 }); });
await page.waitForTimeout(300);
await page.evaluate(() => document.querySelector('.requests')?.scrollIntoView());
await shot('12d-requests');
check('requests board', await page.evaluate(() => !!document.querySelector('.req.have')));
check('fill request', await click('Hand it over'));
await page.waitForTimeout(200);
check('request filled', await page.evaluate(() => (window.__store.getState().g.counts.requestsFilled ?? 0) >= 1));
// Phase 3: staff, tournaments, notices
await page.evaluate(() => document.querySelector('.content').scrollTo(0, 0));
check('staff sheet', await click('👥 Staff'));
await page.waitForTimeout(300);
await page.evaluate(() => { const row = [...document.querySelectorAll('.staff-row')].find((r) => r.textContent.includes('Cashier')); row.querySelector('button').click(); });
await page.waitForTimeout(200);
check('hired cashier', await page.evaluate(() => !!window.__store.getState().g.staff.cashier));
await shot('12e-staff');
await page.click('.modal .x');
await page.evaluate(() => { const s = window.__store; const g = s.getState().g; g.furniture.push({ uid: 9999, type: 'table', tier: 2 }); g.sealed['VEN:pack'] = (g.sealed['VEN:pack'] ?? 0) + 6; s.setState({ rev: s.getState().rev + 1 }); });
check('events sheet', await click('📅 Events'));
await page.waitForTimeout(300);
await page.evaluate(() => { const b = [...document.querySelectorAll('.stepper button')].pop(); b?.click(); b?.click(); });
await page.waitForTimeout(200);
await shot('12f-events');
check('host tournament', await click('Host it tomorrow'));
await page.waitForTimeout(200);
await page.click('.modal .x');
await page.evaluate(() => window.__advance(24));
await page.waitForTimeout(500);
check('tournament result popup', await page.evaluate(() => [...document.querySelectorAll('.levelup-title')].some((b) => b.textContent.includes('results')) || window.__store.getState().g.notices.some((n) => n.title.includes('results'))));
await shot('12g-notice');
await page.evaluate(() => { const s = window.__store; const g = s.getState().g; g.notices = []; g.levelUps = []; s.setState({ rev: s.getState().rev + 1 }); });
// Progression: Goals tab and a level-up popup
await page.evaluate(() => { const s = window.__store; const g = s.getState().g; g.levelUps = []; s.setState({ rev: s.getState().rev + 1 }); });
await click('Goals', 'nav button');
await page.waitForTimeout(400);
check('goals tab', await page.evaluate(() => !!document.querySelector('.level-card') && document.querySelectorAll('.goal').length >= 3));
await shot('13-goals');
await page.evaluate(() => { const s = window.__store; const g = s.getState().g; g.xp = 0; g.level = 2; g.levelUps = [3]; s.setState({ rev: s.getState().rev + 1 }); });
await page.waitForTimeout(400);
check('level-up popup', await page.evaluate(() => !!document.querySelector('.levelup')));
await shot('14-levelup');
await click('Nice');
await page.waitForTimeout(200);
await click('Market', 'nav button');
await page.waitForTimeout(400);
check('locked sets shown', await page.evaluate(() => document.querySelectorAll('.dist-set.locked').length > 0));
await shot('15-market-locked');
await browser.close();
console.log(results.join('\n'));
console.log(errors.length ? 'ERRORS\n' + errors.join('\n') : 'No console errors');
