// Browser check for the UI pass: tip cards, HUD expand/collapse, Help list (iPhone 13).
// Usage: PLAYWRIGHT_PATH=$(npm root -g)/playwright node tools/smoke8.mjs [baseUrl] [outDir]
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
const require = createRequire(import.meta.url);
const { chromium, devices } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const base = process.argv[2] || 'http://localhost:4173/';
const out = process.argv[3] || 'tests/output';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const errors = [];
const results = [];
const check = (name, ok, detail = '') => results.push(`${ok ? 'PASS' : 'FAIL'} ${name} ${detail}`);
const clickText = (page, text, sel = 'button') => page.evaluate(([t, s]) => {
  const el = [...document.querySelectorAll(s)].find((x) => x.textContent.trim().includes(t));
  if (!el) return false;
  el.click();
  return true;
}, [text, sel]);
const ctx = await browser.newContext({ ...devices['iPhone 13'], deviceScaleFactor: 2 });
const page = await ctx.newPage();
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
await page.goto(base + '?quality=low&debug=1', { waitUntil: 'load' });
await page.waitForSelector('.hud', { timeout: 60000 });
await page.waitForTimeout(2500);
check('no tip under the welcome', await page.evaluate(() => !document.querySelector('.tip-card')));
await clickText(page, 'Start operating');
await page.waitForTimeout(1500);
check('first tip', await page.evaluate(() => document.querySelector('.tip-card')?.textContent.includes('Pipes')));
await page.screenshot({ path: `${out}/ui-1-tip.png` });
check('show me', await clickText(page, 'Show a turbine'));
await page.waitForTimeout(800);
check('tip opened turbine', await page.evaluate(() => window.__ui.getState().selectedId !== null));
await page.evaluate(() => window.__ui.getState().select(null));
const pills0 = await page.evaluate(() => document.querySelectorAll('.hud-pill').length);
await page.click('.hud-pill.more');
await page.waitForTimeout(400);
const pills1 = await page.evaluate(() => document.querySelectorAll('.hud-pill').length);
check('hud expands', pills1 > pills0, `${pills0}→${pills1}`);
await page.screenshot({ path: `${out}/ui-2-hud-expanded.png` });
await page.click('.hud-pill.more');
await page.evaluate(() => window.__ui.getState().setPanel('settings'));
await page.waitForTimeout(500);
check('help list', await page.evaluate(() => document.querySelectorAll('.tip-row').length >= 6));
await clickText(page, 'Emergencies', '.tip-row');
await page.waitForTimeout(600);
check('reopen tip', await page.evaluate(() => document.querySelector('.tip-card')?.textContent.includes('alarm')));
await page.screenshot({ path: `${out}/ui-3-reopen.png` });
await browser.close();
console.log(results.join('\n'));
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no console errors');
