// Browser check for staff & shifts: Staff panel, hiring through the UI,
// shift switch, key-person hire (iPhone 13).
// Usage: PLAYWRIGHT_PATH=$(npm root -g)/playwright node tools/smoke5.mjs [baseUrl] [outDir]
import { createRequire } from 'node:module';
import { mkdirSync } from 'node:fs';
const require = createRequire(import.meta.url);
const { chromium, devices } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const base = process.argv[2] || 'http://localhost:4173/';
const out = process.argv[3] || 'tests/output';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const errors = [];
const results = [];
const check = (name, ok, detail = '') => results.push(`${ok ? 'PASS' : 'FAIL'} ${name} ${detail}`);
const clickText = (page, text, sel = 'button') => page.evaluate(([t, s]) => {
  const el = [...document.querySelectorAll(s)].find((x) => x.textContent.trim().includes(t));
  if (!el) return false;
  el.click();
  return true;
}, [text, sel]);
const ctx = await browser.newContext({ ...devices['iPhone 13'], deviceScaleFactor: 2 });
const page = await ctx.newPage();
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
await page.goto(base + '?quality=low&debug=1', { waitUntil: 'load' });
await page.waitForSelector('.hud', { timeout: 60000 });
await page.waitForTimeout(3000);
await clickText(page, 'Start operating');
await page.waitForTimeout(1000);
await page.evaluate(() => { window.__atom().money = 1e6; window.__ui.getState().setPanel('staff'); });
await page.waitForTimeout(1000);
await page.screenshot({ path: `${out}/staff-1.png` });
check('role rows', await page.evaluate(() => document.querySelectorAll('.role-row').length === 5));
const before = await page.evaluate(() => window.__atom().sites.riverside.staff.hired.technician);
await page.click('[aria-label^="Hire one Technician"]');
await page.waitForTimeout(400);
const after = await page.evaluate(() => window.__atom().sites.riverside.staff.hired.technician);
check('hire via UI', after === before + 1, `${before}→${after}`);
check('shift switch', await clickText(page, '2 × 12 hours'));
await page.waitForTimeout(300);
check('shift set', await page.evaluate(() => window.__atom().sites.riverside.staff.shift === '2x12'));
await page.evaluate(() => document.querySelector('.key-slots')?.scrollIntoView());
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/staff-2-key.png` });
const hired = await page.evaluate(() => { const b = [...document.querySelectorAll('.cand button')][0]; b?.click(); return !!b; });
await page.waitForTimeout(500);
check('key person hired', hired && await page.evaluate(() => Object.keys(window.__atom().sites.riverside.staff.key).length === 1));
await page.evaluate(() => document.querySelector('.key-slots')?.scrollIntoView());
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/staff-3-hired.png` });
await browser.close();
console.log(results.join('\n'));
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no console errors');
