export const BUILDINGS: Record<BuildingType, BuildingDef> = Object.fromEntries(
  defs.map((d) => [d.type, d]),
) as Record<BuildingType, BuildingDef>;

export const BUILDING_LIST: BuildingDef[] = defs;

export const CATEGORY_LABEL: Record<BuildingCategory, string> = {
  reactor: 'Reactors',
  power: 'Turbines',
  cooling: 'Cooling',
  grid: 'Grid & Storage',
  support: 'Support',
};

export const CATEGORY_ORDER: BuildingCategory[] = ['reactor', 'power', 'cooling', 'grid', 'support'];

export function isReactor(type: BuildingType): boolean {
  return BUILDINGS[type].category === 'reactor';
}

/** Multiplier applied to a building's base stats at a given level. */
export function levelMult(def: BuildingDef, level: number): number {
  return Math.pow(def.levelGrowth, level - 1);
}

export function upgradeCost(def: BuildingDef, level: number, costMod = 1): number {
  return Math.round(def.cost * def.upgradeBase * Math.pow(def.upgradeGrowth, level - 1) * costMod);
}

/** Upkeep grows more slowly than output with level. */
export function upkeepAt(def: BuildingDef, level: number): number {
  return def.upkeep * Math.pow(1 + (def.levelGrowth - 1) * 0.6, level - 1);
}

export function staffAt(def: BuildingDef, level: number): number {
  return Math.ceil(def.staff * (1 + 0.25 * (level - 1)));
}

export function footprint(def: BuildingDef, rot: number): [number, number] {
  return rot % 2 === 0 ? [def.size[0], def.size[1]] : [def.size[1], def.size[0]];
}
