"""Builds js/official.js and sw-assets.js from the photos in assets/official/.
Run from the project root after adding or changing photos:  python3 tools/make-official-map.py"""
import os,json
P={os.path.splitext(f)[0]:'assets/official/printers/'+f for f in sorted(os.listdir('assets/official/printers'))}
F={os.path.splitext(f)[0]:'assets/official/products/'+f for f in sorted(os.listdir('assets/official/products'))}
R={os.path.splitext(f)[0]:'assets/official/resins/'+f for f in sorted(os.listdir('assets/official/resins'))} if os.path.isdir('assets/official/resins') else {}
open('js/official.js','w').write('/* Generated by tools/make-official-map.py */\nconst OFFICIAL='+json.dumps({'p':P,'f':F,'r':R},indent=1)+';\n')
open('sw-assets.js','w').write('/* Generated by tools/make-official-map.py */\nself.OFFICIAL_FILES='+json.dumps(list(P.values())+list(F.values())+list(R.values()))+';\n')
print(len(P),'printers',len(F),'products',len(R),'resins')
