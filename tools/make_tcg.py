"""Build js/tcg-data.js and assets/tcg/sfd/*.webp from Riot's official Riftbound card gallery
(riftbound.leagueoflegends.com/en-us/card-gallery) and TCGplayer market prices (via tcgcsv.com).
Picks every Spiritforged Overnumbered and Signature card plus 80 random others, seeded so it is repeatable.
Usage: python3 tools/make_tcg.py <scratch dir with next.json prods.json prices.json>"""
import sys,json,random,io,os,re,urllib.request
from PIL import Image
D=sys.argv[1]
nd=json.load(open(os.path.join(D,'next.json')))
cards={}
def walk(o):
    if isinstance(o,dict):
        if 'collectorNumber' in o and 'cardImage' in o: cards[o['id']]=o
        for v in o.values(): walk(v)
    elif isinstance(o,list):
        for v in o: walk(v)
walk(nd)
sfd=[c for c in cards.values() if c['set']['value']['id']=='SFD']
P=json.load(open(os.path.join(D,'prods.json')))['results'];Pr=json.load(open(os.path.join(D,'prices.json')))['results']
price={}
for x in Pr:
    if x.get('marketPrice'):price.setdefault(x['productId'],{})[x['subTypeName']]=x['marketPrice']
bynum={}
for p in P:
    ex={e['name']:e['value'] for e in p['extendedData']}
    if 'Number' in ex:bynum.setdefault(ex['Number'],[]).append((p,price.get(p['productId'],{})))
pack=next(price[p['productId']] for p in P if p['name']=='Spiritforged - Booster Pack')
box=next(price[p['productId']] for p in P if p['name']=='Spiritforged - Booster Display')
case=next(price[p['productId']] for p in P if p['name']=='Spiritforged - Booster Display Case')
def num(c):return c['publicCode'].split('-',1)[1]
def kind(c):
    n=num(c)
    if '*' in n:return 'sig'
    if c['collectorNumber']>221:return 'over'
    if c['rarity']['value']['id']=='showcase':return 'alt'
    return c['rarity']['value']['id']
over=[c for c in sfd if kind(c) in('over','sig')]
rest=[c for c in sfd if kind(c) not in('over','sig')]
random.seed(4217)
want={'common':24,'uncommon':22,'rare':16,'epic':12,'alt':6}
pickd=[]
for k,n in want.items():
    pool=[c for c in rest if kind(c)==k];random.shuffle(pool);pickd+=pool[:n]
sel=over+pickd
out=[]
os.makedirs('assets/tcg/sfd',exist_ok=True)
for c in sel:
    n=num(c);cands=bynum.get(n,[])
    pr=0
    for p,pp in cands:
        v=pp.get('Normal') or pp.get('Foil') or 0
        if kind(c) in('over','sig','alt'):v=pp.get('Foil') or v
        pr=max(pr,v)
    code=re.sub(r'[^0-9a-z]','',n.split('/')[0].lower().replace('*','s'))
    fn=f'assets/tcg/sfd/{code}.webp'
    if not os.path.exists(fn):
        url=c['cardImage']['url'].split('?')[0]
        req=urllib.request.Request(url,headers={'User-Agent':'Mozilla/5.0'})
        for tryn in range(5):
            try:raw=urllib.request.urlopen(req,timeout=40).read();break
            except Exception as e:
                if tryn==4:raise
                import time;time.sleep(2+tryn*2)
        im=Image.open(io.BytesIO(raw)).convert('RGB')
        if c.get('orientation')=='landscape':im=im.rotate(90,expand=True)
        im.thumbnail((372,520));im.save(fn,'WEBP',quality=82)
    out.append({'id':code,'n':c['name'],'no':n,'r':kind(c),'dom':[v['id'] for v in c['domain']['values']],'t':c['cardType']['type'][0]['label'],'p':round(pr or 0.1,2),'img':fn,'ill':(c.get('illustrator') or {}).get('values',[{}])[0].get('label','') if isinstance(c.get('illustrator'),dict) else ''})
out.sort(key=lambda x:x['p'],reverse=True)
js='/* Generated by tools/make_tcg.py from the official Riftbound card gallery and TCGplayer market prices. */\n'
js+='const TCG_SET={id:"SFD",n:"Spiritforged",pack:%s,box:%s,case:%s,cards:%s};\n'%(round(pack.get('Normal',9.5),2),round(box.get('Normal',170),2),round(case.get('Normal',1200),2),json.dumps(out,separators=(',',':')))
open('js/tcg-data.js','w').write(js)
print(len(out),'cards',{k:sum(1 for x in out if x['r']==k) for k in ['sig','over','alt','epic','rare','uncommon','common']},'pack',pack,'top',out[0]['n'],out[0]['p'])
